"""Registry of the sample datasets shipped in ``data/``."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from arbor.preprocessing import read_csv

DATA_DIR = Path(__file__).resolve().parent.parent / "data"


@dataclass(frozen=True)
class Sample:
    file: str
    title: str
    description: str
    source: str

    @property
    def path(self) -> Path:
        return DATA_DIR / self.file


SAMPLES: dict[str, Sample] = {
    "play_tennis": Sample(
        "play_tennis.csv",
        "Play Tennis",
        "14 days of weather and whether tennis was played. Categorical only: the textbook ID3 example.",
        "Quinlan (1986); Mitchell, Machine Learning (1997), table 3.2",
    ),
    "weather_numeric": Sample(
        "weather_numeric.csv",
        "Weather (numeric)",
        "The same 14 days with temperature and humidity as numbers, which shows C4.5's threshold splits.",
        "Quinlan, C4.5: Programs for Machine Learning (1993), table 1-1",
    ),
    "iris": Sample(
        "iris.csv",
        "Iris",
        "150 flowers, 4 numeric measurements, 3 balanced species.",
        "Fisher (1936), UCI Machine Learning Repository",
    ),
    "wine": Sample(
        "wine.csv",
        "Wine",
        "178 wines from three cultivars, 13 numeric results of chemical analysis.",
        "Forina et al., UCI Machine Learning Repository",
    ),
    "breast_cancer": Sample(
        "breast_cancer.csv",
        "Breast Cancer (Wisconsin)",
        "569 tumour biopsies, 30 numeric cell-nucleus features, malignant or benign.",
        "Wolberg, Street & Mangasarian (1995), UCI Machine Learning Repository",
    ),
    "credit_risk": Sample(
        "credit_risk.csv",
        "Credit Risk (synthetic)",
        "600 synthetic loan applications mixing numeric and categorical attributes, 2-5 % missing in four columns.",
        "Generated by scripts/make_datasets.py",
    ),
}


def load_sample(key: str) -> pd.DataFrame:
    return read_csv(SAMPLES[key].path)
